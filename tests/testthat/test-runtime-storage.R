test_that("cleanup requires unchanged reviewed hashes and preserves unrelated bytes", {
  root <- new_parent(); withr::local_options(cttiR.runtime_dir = root)
  cache <- file.path(root, "release-downloads"); dir.create(cache)
  name <- paste0(strrep("a", 64L), ".gguf.part")
  path <- file.path(cache, name); write_bytes("interrupted download", path)
  other <- file.path(cache, "user-notes.txt"); write_bytes("keep", other)
  blob <- file.path(root, "models", "blobs"); dir.create(blob, recursive = TRUE)
  write_bytes("model blob", file.path(blob, "sha256-blob"))
  before <- tree_hashes(root)
  preview <- runtime_cleanup(name)
  expect_equal(tree_hashes(root), before)
  expect_error(runtime_cleanup(name, preview$expected, dry_run = FALSE), "explicit consent")
  expect_error(runtime_cleanup(name, dry_run = FALSE, consent = TRUE), "reviewed hashes")
  write_bytes("changed", path)
  expect_error(runtime_cleanup(name, preview$expected, dry_run = FALSE, consent = TRUE), "changed")
  preview <- runtime_cleanup(name)
  result <- runtime_cleanup(name, preview$expected, dry_run = FALSE, consent = TRUE)
  expect_identical(result$state, "removed"); expect_false(file.exists(path))
  expect_equal(read_document(result$receipt)$state, "removed")
  expect_equal(readLines(other, warn = FALSE), "keep")
  expect_equal(readLines(file.path(blob, "sha256-blob"), warn = FALSE), "model blob")
  expect_false(dir.exists(file.path(root, "setup-lock")))
  expect_error(runtime_cleanup("../outside"), class = "cttir_input_error")
})

test_that("retained releases and active writers protect downloads", {
  f <- release_fixture(); root <- file.path(f$parent, "runtime")
  withr::local_options(cttiR.runtime_dir = root)
  retained <- release_acquire_model(root, f$manifest$model, f$model)
  release <- file.path(root, "releases", f$hash); dir.create(release, recursive = TRUE)
  file.copy(f$path, file.path(release, "manifest.json"))
  before <- tree_hashes(root)
  expect_error(runtime_cleanup(basename(retained)), "protected")
  inventory <- runtime_storage()
  expect_true(inventory$files$retained[inventory$files$path == retained])
  expect_equal(tree_hashes(root), before)
  name <- paste0(strrep("b", 64L), ".gguf.part")
  write_bytes("partial", file.path(root, "release-downloads", name))
  preview <- runtime_cleanup(name)
  lock <- file.path(root, "setup-lock"); dir.create(lock)
  write_bytes("writer", file.path(lock, "owner")); before <- tree_hashes(root)
  expect_error(runtime_cleanup(name, preview$expected, dry_run = FALSE, consent = TRUE), "locked")
  expect_equal(tree_hashes(root), before)
  if (.Platform$OS.type != "windows") {
    link <- file.path(root, "release-downloads", paste0(strrep("c", 64L), ".gguf"))
    expect_true(file.symlink(f$model, link))
    expect_error(runtime_storage(), class = "cttir_path_conflict")
  }
})

test_that("daemon stop targets only a separately previewed owned process", {
  executable <- Sys.which('sleep'); skip_if_not(nzchar(executable))
  root <- new_parent(); withr::local_options(cttiR.runtime_dir = root)
  child <- processx::process$new(executable, '30')
  withr::defer(if (child$is_alive()) child$kill())
  owner <- list(pid = child$get_pid(), host = Sys.info()[['nodename']], endpoint = runtime_endpoint())
  local_mocked_bindings(runtime_owner = function(...) owner)
  before <- tree_hashes(root)
  preview <- runtime_stop()
  expect_identical(preview$state, 'planned'); expect_true(child$is_alive())
  expect_equal(tree_hashes(root), before)
  expect_error(runtime_stop(dry_run = FALSE, expected = preview$expected), 'explicit consent')
  expect_error(runtime_stop(dry_run = FALSE, consent = TRUE, expected = 'stale'), 'identity changed')
  expect_true(child$is_alive())
  if (.Platform$OS.type == "windows") {
    expect_error(runtime_stop(dry_run = FALSE, consent = TRUE, expected = preview$expected),
      "Graceful daemon shutdown is not supported on Windows", class = "cttir_runtime_unavailable")
    expect_true(child$is_alive())
    expect_identical(tree_hashes(root), before)
    expect_false(dir.exists(file.path(root, 'lifecycle-receipts')))
  } else {
    result <- runtime_stop(dry_run = FALSE, consent = TRUE, expected = preview$expected)
    expect_identical(result$state, 'stopped'); expect_false(child$is_alive())
    expect_identical(read_document(result$receipt)$state, 'stopped')
  }
  expect_false(dir.exists(file.path(root, 'setup-lock')))
  local_mocked_bindings(runtime_owner = function(...) NULL)
  expect_error(runtime_stop(), 'No verified owned daemon')
})

test_that("unsupported Windows stop refuses before writes or signals", {
  root <- new_parent(); withr::local_options(cttiR.runtime_dir = root)
  owner <- list(pid = Sys.getpid(), host = Sys.info()[["nodename"]], endpoint = runtime_endpoint())
  local_mocked_bindings(runtime_owner = function(...) owner)
  signals <- 0L
  local_mocked_bindings(ps_terminate = function(...) {
    signals <<- signals + 1L
    stop("Unexpected signal attempt")
  }, .package = "ps")
  stop_windows <- runtime_stop
  platform <- .Platform; platform$OS.type <- "windows"
  environment(stop_windows) <- list2env(list(.Platform = platform), parent = environment(runtime_stop))
  before <- tree_hashes(root)
  preview <- stop_windows()
  expect_identical(preview$state, "planned")
  expect_identical(tree_hashes(root), before)
  expect_error(stop_windows(dry_run = FALSE, expected = preview$expected), "explicit consent")
  expect_error(stop_windows(dry_run = FALSE, consent = TRUE, expected = "stale"), "identity changed")
  expect_error(stop_windows(dry_run = FALSE, consent = TRUE, expected = preview$expected),
    "Graceful daemon shutdown is not supported on Windows", class = "cttir_runtime_unavailable")
  expect_identical(signals, 0L)
  expect_identical(tree_hashes(root), before)
  expect_false(dir.exists(file.path(root, "setup-lock")))
  expect_false(dir.exists(file.path(root, "lifecycle-receipts")))
})
