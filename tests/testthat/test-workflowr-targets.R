test_that("workflowr scheduler is conditional and included in content identities", {
  plain <- workflowr_profile_files("minimal")
  scheduled <- workflowr_profile_files("minimal", "targets")
  expect_false("_targets.R" %in% names(plain))
  expect_true("_targets.R" %in% names(scheduled))
  expect_no_error(parse(text = scheduled[["_targets.R"]]))
  root <- tempfile("scheduler-identity-")
  dir.create(root)
  on.exit(unlink(root, recursive = TRUE))
  writeLines("# first", file.path(root, "_targets.R"))
  env <- new.env(parent = baseenv())
  sys.source(resource_file("templates", "workflowr-0.4.0", "code/R/report_integrity.R"), env)
  expect_contains(env$cr_execution_inputs(root), "_targets.R")
  writeLines("synthetic output", file.path(root, "result.txt"))
  before <- env$cr_begin(root, character())
  writeLines("# changed", file.path(root, "_targets.R"))
  expect_error(env$cr_finish(root, before, "result.txt", character()), "Inputs changed during computation")
})
