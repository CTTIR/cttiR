test_that("static completeness distinguishes warnings from compatibility validity", {
  check <- function(code) validate_generated_code(code, approved_only = FALSE)
  missing <- check("stats::lm()")
  expect_true(attr(missing, "valid"))
  expect_false(attr(missing, "static_complete"))
  expect_true(any(startsWith(missing$reason, "missing_required_argument:")))
  expect_true(attr(check("mean(c(1, 2))"), "static_complete"))
  expect_false(attr(check("# no code"), "static_complete"))
  expect_false(attr(check("mean("), "static_complete"))
  expect_false(attr(check("system('true')"), "static_complete"))
  expect_true(attr(check("mean()"), "valid"))
  expect_false(attr(check("mean()"), "static_complete"))
  expect_true(any(startsWith(check("mean()")$reason, "missing_required_argument:")))
})
