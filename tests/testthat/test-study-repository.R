test_that("study repository checks refuse ancestor discovery", {
  skip_if_not_installed("git2r")
  parent <- withr::local_tempdir()
  parent <- normalizePath(parent, mustWork = TRUE)
  git2r::init(parent)
  child <- file.path(parent, "study")
  dir.create(child)
  expect_error(study_repository(child), "study-owned Git")
  git2r::init(child)
  expect_true(study_repository(child))
  expect_identical(
    normalizePath(git2r::workdir(git2r::repository(child, discover = FALSE)), mustWork = TRUE),
    normalizePath(child, mustWork = TRUE)
  )
  unlink(file.path(child, ".git"), recursive = TRUE)
  expect_error(study_repository(child), "study-owned Git")
})

test_that("study repository checks reject Git indirection and another work tree", {
  skip_if_not_installed("git2r")
  root <- normalizePath(withr::local_tempdir(), mustWork = TRUE)
  other <- normalizePath(withr::local_tempdir(), mustWork = TRUE)
  git2r::init(other)
  writeLines(paste0("gitdir: ", file.path(other, ".git")), file.path(root, ".git"))
  expect_error(study_repository(root), "study-owned Git")
  unlink(file.path(root, ".git"))
  repo <- git2r::init(root)
  git2r::config(repo, core.worktree = other)
  expect_error(study_repository(root), "work directory must equal")
})

test_that("collapsed untracked directories cannot imply committed report source", {
  skip_if_not_installed("git2r")
  root <- normalizePath(withr::local_tempdir(), mustWork = TRUE)
  repo <- git2r::init(root)
  dir.create(file.path(root, "analysis"))
  files <- c("analysis/index.Rmd", "analysis/primary.Rmd")
  for (file in files) writeLines("Synthetic report", file.path(root, file))
  expect_error(study_report_git_status(root, files), "status is ambiguous")
  git2r::add(repo, files)
  expect_true(study_report_git_status(root, files))
  expect_length(git2r::commits(repo), 0L)
  expect_setequal(unlist(git2r::status(repo)$staged, use.names = FALSE), files)
  expect_error(study_report_git_status(root, c(files, "analysis/missing.Rmd")), "status is ambiguous")
})
