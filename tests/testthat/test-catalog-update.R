  expect_equal(nrow(search("cttirFixtureA::old")), 1L)
})

test_that("combined local refresh preserves curation and historical resource pins", {
  f <- local_update_fixture()
  description <- readLines(file.path(f$source, "DESCRIPTION"))
  writeLines(sub("cttirFixtureA", "reflowR", description, fixed = TRUE), file.path(f$source, "DESCRIPTION"))
  old <- resources("reflowR", limit = 100)
  project <- project("Historical resources", "methods", "Goal", f$parent)
  result <- update()
  current <- resources("reflowR", limit = 100)
  expect_true(result$activation)
  expect_equal(nrow(current), nrow(old) + 1L)
  expect_true(all(current$purpose == old$purpose[[1]]))
  expect_true(all(current$adapter_status == old$adapter_status[[1]]))
  expect_true(any(current$repository == "Local" & current$observed_version == "1.0.0"))
  expect_equal(resources("reflowR", path = project$path, limit = 100), old)
  expect_equal(update()$status, "unchanged")
  expect_true(rollback_knowledge(result$previous_id, dry_run = FALSE)$activation)
  expect_equal(resources("reflowR", limit = 100), old)
})

