test_that("update preview leaves no store and rejects unsupported policies", {
  f <- local_update_fixture()
  plan <- update(dry_run = TRUE)
  expect_equal(plan$status, "planned")
  expect_false(plan$activation)
  expect_false(file.exists(f$store))
  expect_equal(update_knowledge(dry_run = TRUE)$new_id, plan$new_id)
  expect_error(update(mode = "remote"), class = "cttir_source_unavailable")
  expect_error(update(catalogs = "invalid"), class = "cttir_input_error")
  expect_error(update(sources = "missing", dry_run = TRUE), class = "cttir_input_error")
  expect_error(update(packages = "missing", dry_run = TRUE), class = "cttir_source_unavailable")
  expect_false(file.exists(f$store))
})

test_that("whole package updates remove exports, retain pins and roll back", {
  f <- local_update_fixture()
  first <- update()
  expect_true(first$activation)
  expect_equal(nrow(search("cttirFixtureA::old")), 1L)
  project <- project("Pinned project", "methods", "Goal", f$parent)
  pinned_files <- tree_hashes(project$path)
  writeLines(c("keep <- function(x = 2) x", "new <- function(y) y"), file.path(f$source, "R", "api.R"))
  writeLines(c("export(keep)", "export(new)"), file.path(f$source, "NAMESPACE"))
  second <- update()
  expect_true(second$activation)
  expect_true(any(second$api_diff$change == "export_removed" & second$api_diff$symbol == "old"))
  expect_true(any(second$api_diff$change == "export_changed" & second$api_diff$symbol == "keep"))
  expect_equal(nrow(search("cttirFixtureA::old")), 0L)
  expect_equal(nrow(search("cttirFixtureA::new")), 1L)
  expect_equal(nrow(search("cttirFixtureA::old", path = project$path)), 1L)
  expect_equal(tree_hashes(project$path), pinned_files)
  expect_equal(update()$status, "unchanged")
  before <- tree_hashes(f$store)
  expect_equal(rollback_knowledge(first$new_id)$status, "planned")
  expect_equal(tree_hashes(f$store), before)
  expect_true(rollback_knowledge(first$new_id, dry_run = FALSE)$activation)
  expect_equal(nrow(search("cttirFixtureA::old")), 1L)
  expect_equal(nrow(search("cttirFixtureA::new")), 0L)
  expect_equal(tree_hashes(project$path), pinned_files)
})

