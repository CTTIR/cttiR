    expect_match(as.character(output$packages$html), "Exports", fixed = TRUE)
    session$setInputs(mode = "local", catalogs = c("knowledge", "resources"), sources = "", packages_filter = "")
    session$setInputs(apply_update = 1)
    expect_equal(state$status$key, "knowledge.preview_first")
    before <- current_catalog_manifest()$manifest_id
    session$setInputs(preview_update = 1)
    expect_equal(state$update_preview$status, "planned")
    expect_identical(state$update_preview$previous_id, before)
    expect_identical(current_catalog_manifest()$manifest_id, before)
    html <- as.character(output$update_result$html)
    expect_match(html, "package_added", fixed = TRUE)
    expect_match(html, "No package is installed", fixed = TRUE)
    session$setInputs(sources = "fixture")
    session$setInputs(apply_update = 2)
    expect_equal(state$status$key, "knowledge.preview_first")
    session$setInputs(sources = "")
    session$setInputs(apply_update = 3)
    expect_true(state$update_result$activation)
    after <- current_catalog_manifest()$manifest_id
    expect_false(identical(after, before))
    session$setInputs(rollback_id = before, preview_rollback = 1)
    expect_equal(state$rollback_preview$status, "planned")
    expect_identical(current_catalog_manifest()$manifest_id, after)
    session$setInputs(apply_rollback = 1)
    expect_equal(state$status$key, "knowledge.rollback_applied")
    expect_identical(current_catalog_manifest()$manifest_id, before)
  })
