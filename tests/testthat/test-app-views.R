test_that("Resources load lazily and apply domain, repository and maturity filters", {
  skip_if_not_installed("shiny")
  counter <- new.env(parent = emptyenv())
  visible <- shiny::reactiveVal(FALSE)
  shiny::testServer(app_resources_server, args = app_test_args(counting_worker(counter), visible = visible), {
    session$setInputs(query = "", domain = "", repository = "", maturity = "", limit = 50, use_project = FALSE)
    expect_length(counter$calls, 0L)
    visible(TRUE)
    session$flushReact()
    expect_equal(counter$calls, "resources")
    expect_true("cytometry" %in% state$facets$domain)
    expect_true("CRAN" %in% state$facets$repository)
    expect_lte(nrow(state$results), 50L)
    visible(FALSE)
    visible(TRUE)
    session$flushReact()
    expect_length(counter$calls, 1L)
    session$setInputs(domain = "cytometry", repository = "Bioconductor", search = 1)
    expect_gt(nrow(state$results), 0L)
    expect_true(all(state$results$category == "cytometry"))
    expect_true(all(state$results$repository == "Bioconductor"))
    html <- as.character(output$results$html)
    expect_match(html, "Candidate", fixed = TRUE)
    expect_match(html, 'data-label="Maturity"', fixed = TRUE)
    session$setInputs(maturity = "tested")
    expect_equal(nrow(filtered()), 0L)
    session$setInputs(limit = 0, search = 2)
    expect_equal(state$status$key, "resources.limit_invalid")
  })
  status <- app_resource_maturity(data.frame(adapter_status = c("not_implemented", "adapter_tested", "untested", NA)))
  expect_equal(status, c("candidate", "tested", "candidate", "candidate"))
})

test_that("Audit filters checks, exports reports and applies allowlisted repairs", {
  skip_if_not_installed("shiny")
  p <- project("Audit fixture", "methods", "Goal", new_parent())
  reports <- file.path(new_parent(), "reports")
  shiny::testServer(app_audit_server, args = app_test_args(project = shiny::reactive(p$path)), {
    session$setInputs(scope = "project", path = p$path, live = FALSE, show = app_audit_statuses, required_only = FALSE)
    session$setInputs(repair = 1)
    expect_equal(state$status$key, "audit.repair_preview_first")
    session$setInputs(run = 1)
    expect_s3_class(state$result, "cttir_audit")
    expect_match(as.character(output$summary$html), "Overall status", fixed = TRUE)
    expect_match(as.character(output$repair_preview$html), "No failed check", fixed = TRUE)
    unlink(file.path(p$path, "code", "validate_project.R"))
    session$setInputs(run = 2)
    expect_equal(state$result$overall_status, "fail")
    preview <- as.character(output$repair_preview$html)
    expect_match(preview, "PRJ-002", fixed = TRUE)
    expect_match(preview, "code/validate_project.R", fixed = TRUE)
    expect_match(as.character(output$summary$html), "allowlisted repair", fixed = TRUE)
    session$setInputs(show = "fail")
    expect_match(as.character(output$checks$html), "validate_project.R", fixed = TRUE)
    expect_false(grepl("Baseline matches", as.character(output$checks$html), fixed = TRUE))
    session$setInputs(repair = 2)
    expect_true(file.exists(file.path(p$path, "code", "validate_project.R")))
    expect_length(state$repaired, 1L)
    expect_equal(state$status$key, "audit.repaired")
    session$setInputs(output = reports, export = 1)
    expect_length(state$reports, 2L)
    expect_true(all(file.exists(state$reports)))
    expect_true(all(startsWith(state$reports, reports)))
    session$setInputs(scope = character(0))
    session$setInputs(run = 3)
    expect_equal(state$status$key, "audit.scope_required")
  })
})

