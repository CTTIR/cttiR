counting_worker <- function(counter) {
  counter$calls <- character()
  function(operation, args) {
    counter$calls <- c(counter$calls, operation)
    app_test_worker(operation, args)
  }
}

test_that("Ask renders grounded evidence, escapes text and never runs returned code", {
  skip_if_not_installed("shiny")
  shiny::testServer(app_ask_server, args = app_test_args(), {
    session$setInputs(action = "ask", question = "", verified_only = TRUE, use_project = FALSE, limit = 20)
    session$setInputs(run = 1)
    expect_equal(state$status$key, "ask.empty")
    session$setInputs(question = "annotatR <script>alert(1)</script>", run = 2)
    expect_s3_class(state$result, "cttir_answer")
    html <- as.character(output$result$html)
    expect_false(grepl("<script>alert", html, fixed = TRUE))
    expect_match(html, "Limitations", fixed = TRUE)
    session$setInputs(action = "search", question = "annotatR", run = 3)
    expect_s3_class(state$result, "data.frame")
    expect_match(as.character(output$result$html), "Search results", fixed = TRUE)
  })
  fields <- list(answer = "Use the reviewed adapter.", steps = list("pkg::fn(x)"),
    code = "file.create('/tmp/cttir-should-never-exist')", citations = list("https://example.org/doc", "javascript:alert(1)"),
    verification_levels = "static_api_verified", evidence = data.frame(), limitations = "Synthetic.",
    future_field = list(note = "added by a newer ask()"))
  answer <- structure(fields, class = "cttir_answer")
  worker <- function(operation, args) {
    list(is_alive = function() FALSE, get_result = function() list(ok = TRUE, value = answer), kill = function() NULL)
  }
  shiny::testServer(app_ask_server, args = app_test_args(worker), {
    session$setInputs(action = "ask", question = "How?", verified_only = TRUE, use_project = FALSE, run = 1)
    html <- as.character(output$result$html)
    expect_match(html, "file.create", fixed = TRUE)
    expect_match(html, "data-copy-target", fixed = TRUE)
    expect_match(html, 'href="https://example.org/doc"', fixed = TRUE)
    expect_false(grepl('href="javascript', html, fixed = TRUE))
    expect_match(html, "Other details", fixed = TRUE)
    expect_match(html, "added by a newer ask()", fixed = TRUE)
  })
  expect_false(file.exists("/tmp/cttir-should-never-exist"))
})

test_that("Knowledge previews and applies an update against a temporary store, then rolls back", {
