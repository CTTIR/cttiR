test_that("the paired example preserves results through explicit browser steps", {
  skip_if_not_installed("reflowR")
  skip_if_not_installed("workflowr")
  skip_if_not(rmarkdown::pandoc_available())
  live <- browser_app("paired-study", "cttiR::setup_app(launch.browser = FALSE)")
  app <- live$app
  app$click("home-go_study")
  directory <- file.path(live$projects, "paired_example")
  withr::defer(Sys.chmod(file.path(directory, "data/raw"), "0755"))
  app$set_inputs(`study-recipe` = "paired", `study-directory` = directory,
    `study-author` = "Test group", `study-synthetic_acknowledged` = TRUE,
    `study-independent_pairs` = TRUE)
  app$click("study-preview", wait_ = FALSE)
  wait_text(app, "#study-review", "Contract previewed")
  expect_false(dir.exists(directory))
  app$wait_for_js("!document.getElementById('study-compile').disabled")
  app$click("study-compile", wait_ = FALSE)
  wait_text(app, "#study-review", "Structural scaffold compiled", timeout = 180000)
  app$wait_for_js("!document.getElementById('study-run').disabled")
  app$click("study-run", wait_ = FALSE)
  wait_text(app, "#study-review", "Synthetic analysis recorded", timeout = 180000)
  numerical <- tree_hashes(file.path(directory, "output/analysis"))
  fixture <- app_study_fixture("paired")
  direct <- study_analyze(fixture$spec, fixture$data, fixture$units)
  stored <- jsonlite::read_json(file.path(directory, "output/analysis/results.json"), simplifyVector = TRUE)
  expect_equal(stored$coefficients, direct$coefficients, tolerance = 0)
  app$wait_for_js("!document.getElementById('study-render').disabled")
  app$click("study-render", wait_ = FALSE)
  wait_text(app, "#study-review", "Synthetic report verified", timeout = 600000)
  expect_identical(tree_hashes(file.path(directory, "output/analysis")), numerical)
  expect_length(list.files(file.path(directory, "docs"), pattern = "\\.html$"), 12L)
  declaration_path <- file.path(live$parent, "external-declaration.rds")
  app$get_download("study-declaration", filename = declaration_path)
  declaration <- readRDS(declaration_path)
  recorded <- declaration$render$files
  actual <- lapply(names(recorded), function(path) digest::digest(file = file.path(directory, path), algo = "sha256"))
  expect_identical(stats::setNames(actual, names(recorded)), recorded)
  expect_match(app$get_text("#study-review"), "Scientific review remains pending", fixed = TRUE)
  capture(app, "paired-report", "#study-review")
})
